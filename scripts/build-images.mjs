#!/usr/bin/env node
/**
 * Optimises the site's screenshots: every JPG or PNG in content/images/ (the originals, never served)
 * becomes WebP in public/screenshots/, at its own width (at most 1800px) as <name>.webp plus smaller
 * copies for srcset (<name>-480.webp, <name>-960.webp, …), and src/lib/images.generated.ts lists
 * them with their sizes. Run after adding or changing an image; the outputs are committed, so builds
 * don't need it.
 *
 * Use an image by its name: a project's Screenshot (Settings, which lists /screenshots/<name>.webp),
 * or `image: <name>` at the top of a journey post (content/journey/<slug>.md).
 * Usage: npm run build:images
 */
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const SOURCE = "content/images";
const OUT = "public/screenshots";
const MAX = 1800;
const WIDTHS = [480, 960, 1440];

mkdirSync(OUT, { recursive: true });
// Start clean, so a removed original doesn't leave its copies behind. README.txt stays.
for (const name of readdirSync(OUT)) if (name.endsWith(".webp")) rmSync(`${OUT}/${name}`);

const images = {};
const sources = existsSync(SOURCE) ? readdirSync(SOURCE).filter((n) => /^[a-z0-9-]+\.(jpe?g|png)$/i.test(n)).sort() : [];
for (const file of sources) {
	const name = file.replace(/\.[^.]+$/, "").toLowerCase();
	const meta = await sharp(`${SOURCE}/${file}`).metadata();
	const width = Math.min(meta.width, MAX);
	const height = Math.round((meta.height * width) / meta.width);
	const widths = [...WIDTHS.filter((w) => w < width), width];
	for (const w of widths) {
		const out = w === width ? `${OUT}/${name}.webp` : `${OUT}/${name}-${w}.webp`;
		await sharp(`${SOURCE}/${file}`).resize({ width: w }).webp({ quality: 80, effort: 6 }).toFile(out);
	}
	images[name] = { width, height, widths };
}

writeFileSync(
	"src/lib/images.generated.ts",
	`// Generated by scripts/build-images.mjs from content/images/. Don't edit by hand.\n` +
		`/** Each screenshot by name: its full size, and the widths of its WebP copies in public/screenshots/ (the last is the full size, <name>.webp). */\n` +
		`export const IMAGES: Record<string, { width: number; height: number; widths: number[] }> = ${JSON.stringify(images, null, "\t")};\n`,
);
console.log(`✓ build-images: ${sources.length} image${sources.length === 1 ? "" : "s"} from ${SOURCE}/ into ${OUT}/`);
