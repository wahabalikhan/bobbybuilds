#!/usr/bin/env node
/**
 * Lists the image files in public/logos/ into src/lib/logos.generated.ts, so settings can offer
 * them (the Worker can't read the file system). Runs before dev and build; tests check it's current.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const files = readdirSync("public/logos")
	.filter((name) => /^[A-Za-z0-9._-]+\.(png|jpe?g|webp|svg|gif)$/i.test(name))
	.sort()
	.map((name) => `/logos/${name}`);

// The profile photo can be public/profile.png, .jpg, .jpeg or .webp: whichever is added.
const photo = ["png", "jpg", "jpeg", "webp"].map((ext) => `profile.${ext}`).find((name) => existsSync(`public/${name}`)) ?? null;
const out = `// Generated by scripts/build-logos.mjs from public/logos/ and public/profile.*. Don't edit by hand.\nexport const LOGOS: string[] = ${JSON.stringify(files, null, "\t")};\n\n/** The profile photo's path (public/profile.png or .jpg, …), or null until one is added (the initial is shown). */\nexport const PROFILE_PHOTO: string | null = ${JSON.stringify(photo ? `/${photo}` : null)};\n`;
const path = "src/lib/logos.generated.ts";
let current = "";
try {
	current = readFileSync(path, "utf8");
} catch {}
if (current !== out) writeFileSync(path, out);
console.log(`✓ build-logos: ${files.length} logo${files.length === 1 ? "" : "s"} in public/logos/; profile photo ${photo ?? "not added yet"}`);
