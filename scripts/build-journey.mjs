#!/usr/bin/env node
/**
 * Reads the journey posts in content/journey/<slug>.md into src/lib/journey-posts.generated.ts (the
 * Worker can't read files). Runs before dev, build and typecheck.
 *
 * Each file is named after its journey entry's slug (shown on the entry in the admin) and is optional:
 * an entry without one still gets its post page, showing its text. A file has a short header, then
 * the post in Markdown:
 *
 *   ---
 *   image: rtj-desktop                  (optional: a screenshot's name, from content/images/)
 *   imageAlt: What the screenshot shows (required with an image)
 *   numbers:                            (optional: "The numbers" card, one "Label: value" per line)
 *     Before: ~5,000
 *     Today: {open_jobs}                (a live public number of the entry's project)
 *   ---
 *   ## What changed
 *   …
 *
 * In the post, `> A line` is a pull quote, and {key} is a live public number of the entry's project.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const DIR = "content/journey";
const images = existsSync("content/images") ? readdirSync("content/images").map((n) => n.replace(/\.[^.]+$/, "").toLowerCase()) : [];
const problems = [];
const posts = {};

for (const file of existsSync(DIR) ? readdirSync(DIR).filter((n) => n.endsWith(".md")).sort() : []) {
	const slug = file.slice(0, -3);
	const where = `${DIR}/${file}`;
	if (!/^[a-z0-9-]{1,80}$/.test(slug)) problems.push(`${where}: the name must be the entry's slug (a-z, 0-9 and -).`);
	const source = readFileSync(where, "utf8").replace(/\r\n/g, "\n");
	const match = source.match(/^---\n([\s\S]*?)\n?---\n?([\s\S]*)$/);
	const header = match ? match[1] : "";
	const body = (match ? match[2] : source).trim();

	const post = { image: null, imageAlt: "", numbers: [], body };
	let inNumbers = false;
	for (const line of header.split("\n")) {
		if (!line.trim()) continue;
		const nested = /^\s+/.test(line);
		const [, key, value = ""] = line.trim().match(/^([^:]+):\s*(.*)$/) ?? [];
		if (key === undefined) {
			problems.push(`${where}: "${line.trim()}" should be "name: value".`);
			continue;
		}
		if (nested && inNumbers) {
			post.numbers.push({ label: key.trim(), value: value.trim() });
			continue;
		}
		inNumbers = false;
		if (key === "image") post.image = value.trim().toLowerCase() || null;
		else if (key === "imageAlt") post.imageAlt = value.trim();
		else if (key === "numbers") inNumbers = true;
		else problems.push(`${where}: unknown setting "${key}" (use image, imageAlt or numbers).`);
	}
	if (post.image && !images.includes(post.image)) problems.push(`${where}: no image "${post.image}" in content/images/.`);
	if (post.image && !post.imageAlt) problems.push(`${where}: add imageAlt, describing the image for people who can't see it.`);
	if (post.numbers.some((n) => !n.label || !n.value)) problems.push(`${where}: each number needs a label and a value ("Before: ~5,000").`);
	posts[slug] = post;
}

if (problems.length) {
	console.error(`✗ build-journey:\n  ${problems.join("\n  ")}`);
	process.exit(1);
}

writeFileSync(
	"src/lib/journey-posts.generated.ts",
	`// Generated by scripts/build-journey.mjs from content/journey/. Don't edit by hand.\n` +
		`export type JourneyPostSource = { image: string | null; imageAlt: string; numbers: { label: string; value: string }[]; body: string };\n\n` +
		`/** Each journey post's extras by its entry's slug: the hero image, "The numbers" and the Markdown body. */\n` +
		`export const POSTS: Record<string, JourneyPostSource> = ${JSON.stringify(posts, null, "\t")};\n`,
);
console.log(`✓ build-journey: ${Object.keys(posts).length} post${Object.keys(posts).length === 1 ? "" : "s"} from ${DIR}/`);
